"""Read-only sample assets served by the backend itself (CLV-67).

The ical plugin fetches calendar feeds over HTTP, so the sample calendar is
served from here instead of a second HTTP server. The file lives under the
data dir, so it works unchanged in Docker and is regenerated by
``python -m app.demo seed``.
"""

from pathlib import Path

from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse

from app.config import settings
from app.demo.seed import CALENDAR_ICS_NAME, DEMO_DIRNAME

router = APIRouter()


def _demo_calendar_path() -> Path:
    return Path(settings.data_dir) / DEMO_DIRNAME / CALENDAR_ICS_NAME


@router.get("/demo/calendar.ics", response_class=FileResponse)
async def demo_calendar():
    """The seeded sample calendar feed (404 until ``app.demo seed`` runs)."""
    path = _demo_calendar_path()
    if not path.is_file():
        raise HTTPException(
            status_code=404,
            detail="No sample calendar is seeded. Run: python -m app.demo seed",
        )
    return FileResponse(
        path,
        media_type="text/calendar; charset=utf-8",
    )
